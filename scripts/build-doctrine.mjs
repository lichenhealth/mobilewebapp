#!/usr/bin/env node
/**
 * ONE SOURCE OF TRUTH FOR EVERY ASSISTANT (founder 2026-08-16: "I want him to
 * have as much of your context, knowledge and wisdom as possible").
 *
 * The problem was never how much to copy — it's that every copy rots. The
 * hand-typed PLATFORM_MAP in claude-chat was four hours old and already
 * missing pronouns; APP_OVERVIEW.md, written for exactly this purpose, was a
 * week stale. CLAUDE.md is the one document that can't drift, because
 * updating it is part of shipping.
 *
 * So: generate the assistants' knowledge FROM CLAUDE.md rather than writing a
 * second description of the same platform. Run before deploying any edge
 * function that talks to members:
 *
 *     node scripts/build-doctrine.mjs && supabase functions deploy <name>
 *
 * Edge functions can't read the repo at runtime — they only carry what was
 * bundled at deploy — so this writes a TS module they import.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execSync } from 'node:child_process';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'supabase/functions/_shared/doctrine.ts');

const SOURCES = [
  ['CLAUDE.md', 'The project brain: how Lichen works and WHY it was built this way.'],
  ['docs/ASSISTANT_ACTIONS.md', 'What an assistant may and may not do on a member’s behalf.'],
];

/** How an assistant must handle a developer's document. Without this it will
 *  quote column names and RLS policies at a confused member. */
const RULE = `HOW TO USE WHAT FOLLOWS

This is Lichen's own engineering documentation. It is given to you so your
answers are TRUE and current, not so you can recite it.

- TRANSLATE, never quote. A member asking why they can't find someone should
  hear "they've set themselves unfindable", never "profiles.findable" or the
  name of a policy, table, migration or edge function.
- The DOCTRINE is the valuable part, not the schema. Why there are no counts.
  Why unknown is never yes. Why a confused member is a design bug, not a user
  error. That reasoning is what makes an answer sound like Lichen.
- Anything marked as vision, open, planned or not-yet-built DOES NOT EXIST.
  Never describe it as something a member can use today.
- If the documentation contradicts what a member is seeing, believe the
  member and say you're not sure. The docs describe intent; their screen is
  the fact.`;

const parts = [];
for (const [rel, what] of SOURCES) {
  let text;
  try { text = readFileSync(join(root, rel), 'utf8'); }
  catch { console.warn(`  (skipped ${rel} — not found)`); continue; }
  parts.push(`\n\n===== ${rel} — ${what} =====\n\n${text.trim()}`);
  console.log(`  + ${rel.padEnd(28)} ${String(text.length).padStart(7)} bytes`);
}

// RECENTLY SHIPPED (founder 2026-11-08: "how can it see what you've done and
// know what's new, so i can keep building with you but not have to brief
// it"): the newest merged ship titles ride along, dated, so an assistant
// knows what changed even before it reads the long-form doc. Squash-merge
// subjects on main ARE the changelog.
let recent = '';
try {
  const log = execSync("git log --first-parent -n 40 --date=short --pretty=format:'%ad  %s' HEAD", { cwd: root, encoding: 'utf8' })
    .split('\n').filter((l) => l && !/\bMerge (main|branch|remote)/i.test(l)).slice(0, 30);
  if (log.length) {
    recent = `\n\n===== RECENTLY SHIPPED — the newest ships, newest first (YYYY-MM-DD  title). If a member asks "what's new", start here; the details live in CLAUDE.md below. Something a member says was built that appears neither here nor below is NOT built — say so plainly and offer to file it with file_dev_report. =====\n\n${log.join('\n')}`;
    console.log(`  + recent ships               ${String(log.length).padStart(7)} lines`);
  }
} catch { console.warn('  (skipped recent ships — no git history here)'); }

const body = `${RULE}${recent}${parts.join('')}`;
const banner = `// GENERATED by scripts/build-doctrine.mjs — do not edit.
// Source: ${SOURCES.map(([r]) => r).join(', ')}
// Regenerate and redeploy whenever the docs change:
//   node scripts/build-doctrine.mjs && supabase functions deploy <name>
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, `${banner}\nexport const LICHEN_DOCTRINE = ${JSON.stringify(body)};\n`);

const tokens = Math.round(body.length / 4);
console.log(`\n  → ${OUT.replace(root + '/', '')}`);
console.log(`    ${body.length} bytes  ~${tokens} tokens (prompt-cached, so paid once per cache window)`);
